#!/usr/bin/env bash
# Write a NEW group_vars/all/vault.yml with freshly generated secrets (plaintext; encrypt it next).
#
#   infra/ansible/scripts/new-vault.sh [output file]      # default: group_vars/all/vault.yml
#   ansible-vault encrypt infra/ansible/group_vars/all/vault.yml
#
# Generated: every password and key we own (DB users, Patroni users, ARI, Garage, S3 key, JWT,
# test SIP users, Grafana admin). CHANGE_ME: values that come from the Course Services tab (PSTN vendor digest
# credentials, Stripe test keys, DIDWW Api-Key); fill those in before encrypting.
#
# One vault per deployment, shared by everyone who deploys it: the db cluster, Garage and every
# service must see the SAME values. Regenerating it for a running system breaks replication,
# Garage and SIP logins, so do it only before the first deploy (or rotate deliberately).
# Never commit the plaintext. Share the encrypted file + the vault password over separate channels.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$here/group_vars/all/vault.yml}

if [ -e "$out" ] && [ "${FORCE:-}" != 1 ]; then
  echo "refusing to overwrite $out (it may hold the secrets of a running system)." >&2
  echo "Move it away first, or run with FORCE=1." >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "openssl not found" >&2; exit 1; }

hex() { openssl rand -hex "$1"; }

umask 077
cat >"$out" <<EOF
# Generated by infra/ansible/scripts/new-vault.sh on $(date -u +%Y-%m-%dT%H:%MZ).
# Encrypt before sharing or deploying:  ansible-vault encrypt group_vars/all/vault.yml
# Keys and formats: group_vars/all/vault.yml.example

# Postgres app/Kamailio users, ARI.
vault_db_app_password: $(hex 24)
vault_db_kamailio_password: $(hex 24)
vault_ari_password: $(hex 24)

# Patroni cluster: superuser, streaming replication, pg_rewind.
vault_db_superuser_password: $(hex 24)
vault_db_replication_password: $(hex 24)
vault_db_rewind_password: $(hex 24)

# Garage: rpc secret (32 bytes hex) and the S3 key imported into it (GK + 24 hex / 64 hex).
vault_garage_rpc_secret: $(hex 32)
vault_s3_access_key: GK$(hex 12)
vault_s3_secret_key: $(hex 32)

# API: signs auth cookies (same on every app node).
vault_jwt_secret: $(hex 32)
# API: bearer token for the provider-only routes (/operator/..., support tickets of all accounts).
vault_operator_token: $(hex 32)

# Seeded test staff (alice = browser, bob = UDP phone / SIPp). SIP port 5060 is public: keep these
# random, they can place billed vendor calls.
vault_test_alice_password: $(hex 12)
vault_test_bob_password: $(hex 12)

# Monitoring (mon-1): Grafana "admin" password. Discord webhook for alerts: paste it from the
# channel's settings (Integrations -> Webhooks); empty = alerts only in Grafana's Alerting pages.
vault_grafana_admin_password: $(hex 16)
vault_discord_webhook_url: ""

# ---- From the Course Services tab: fill in ------------------------------------------------
# PSTN vendor digest credentials.
vault_vendor_us_user: CHANGE_ME
vault_vendor_us_password: CHANGE_ME
vault_vendor_intl_user: CHANGE_ME
vault_vendor_intl_password: CHANGE_ME
# Payment gateway (Stripe clone) test-mode keys.
vault_stripe_secret_key: CHANGE_ME
vault_stripe_publishable_key: CHANGE_ME
# DID provider (DIDWW v3 clone) Api-Key.
vault_did_api_key: CHANGE_ME
EOF

echo "wrote $out"
echo "next: fill in the CHANGE_ME values, then: ansible-vault encrypt $out"
